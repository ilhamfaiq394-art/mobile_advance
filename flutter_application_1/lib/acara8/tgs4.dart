void main() {
  var tanggal = 15; // assign nilai variabel tanggal disini (1 - 31)
  var bulan = 4;    // assign nilai variabel bulan disini (1 - 12)
  var tahun = 2007; // assign nilai variabel tahun disini (1900 - 2200)

  String namaBulan = "";

  switch (bulan) {
    case 1:
      namaBulan = "Januari";
      break;
    case 2:
      namaBulan = "Februari";
      break;
    case 3:
      namaBulan = "Maret";
      break;
    case 4:
      namaBulan = "April";
      break;
    case 5:
      namaBulan = "Mei";
      break;
    case 6:
      namaBulan = "Juni";
      break;
    case 7:
      namaBulan = "Juli";
      break;
    case 8:
      namaBulan = "Agustus";
      break;
    case 9:
      namaBulan = "September";
      break;
    case 10:
      namaBulan = "Oktober";
      break;
    case 11:
      namaBulan = "November";
      break;
    case 12:
      namaBulan = "Desember";
      break;
    default:
      namaBulan = "Bulan tidak valid";
  }

  print("$tanggal $namaBulan $tahun");
}